#!/usr/bin/env python3
"""
digit_touch: export a few MNIST test images to C, along with the
EXACT int8 output the model gives on the PC.

The board will run the same model on the same images: if TFLM is properly
integrated, it must reproduce these outputs byte for byte.

Usage:  python export_samples.py   (after quantize.py)
Output: src/test_images.c / .h
"""

import os
from pathlib import Path

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
os.environ.setdefault("CUDA_VISIBLE_DEVICES", "")

import numpy as np
from tensorflow import keras

from quantize import make_interpreter

TRAIN_DIR = Path(__file__).resolve().parent
OUT = TRAIN_DIR / "out"
SRC = TRAIN_DIR.parent / "src"
N_ERRORS = 2    # besides one example per digit, a few images the model gets wrong


def main():
    _, (x_test, y_test) = keras.datasets.mnist.load_data()
    interp = make_interpreter((OUT / "model_int8.tflite").read_bytes())
    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    in_scale, in_zp = inp["quantization"]

    def quantize(img_u8):
        x = img_u8.astype(np.float32) / 255.0
        return np.clip(np.round(x / in_scale) + in_zp, -128, 127).astype(np.int8)

    def run(q):
        interp.set_tensor(inp["index"], q.reshape(1, 28, 28, 1))
        interp.invoke()
        return interp.get_tensor(out["index"])[0].copy()

    # All test outputs, to find examples of errors
    outputs = np.stack([run(quantize(img)) for img in x_test])
    preds = outputs.argmax(1)

    chosen = [int(np.where(y_test == d)[0][0]) for d in range(10)]   # 1st example of each digit
    errors = np.where(preds != y_test)[0]
    chosen += [int(i) for i in errors[:N_ERRORS]]

    images = [quantize(x_test[i]) for i in chosen]
    expected = [outputs[i] for i in chosen]
    labels = [int(y_test[i]) for i in chosen]

    def c_rows(values, per_line):
        v = [str(int(a)) for a in values]
        return "\n".join("\t\t" + ", ".join(v[i:i + per_line]) + ","
                         for i in range(0, len(v), per_line))

    n = len(chosen)
    (SRC / "test_images.h").write_text(f"""/*
 * MNIST test images — FILE GENERATED by train/export_samples.py.
 *
 * Indices in the MNIST test set: {chosen}
 * The last {N_ERRORS} are images the model gets wrong (on the PC too).
 */

#ifndef TEST_IMAGES_H_
#define TEST_IMAGES_H_

#include <stdint.h>

#define TEST_IMAGE_COUNT {n}

/* Already quantized images (int8, -128 = black, 127 = white), 28x28 row by row */
extern const int8_t test_images[TEST_IMAGE_COUNT][28 * 28];
/* True digit of each image */
extern const uint8_t test_labels[TEST_IMAGE_COUNT];
/* Exact int8 output of the model on the PC, to be matched byte for byte on the board */
extern const int8_t test_expected[TEST_IMAGE_COUNT][10];

#endif /* TEST_IMAGES_H_ */
""")

    body = ["/* FILE GENERATED by train/export_samples.py, do not edit. */\n",
            '#include "test_images.h"\n',
            "const int8_t test_images[TEST_IMAGE_COUNT][28 * 28] = {"]
    for i, img in zip(chosen, images):
        body.append(f"\t{{ /* MNIST test #{i}, digit {y_test[i]} */")
        body.append(c_rows(img.ravel(), 28))
        body.append("\t},")
    body.append("};\n")
    body.append("const uint8_t test_labels[TEST_IMAGE_COUNT] = { "
                + ", ".join(map(str, labels)) + " };\n")
    body.append("const int8_t test_expected[TEST_IMAGE_COUNT][10] = {")
    for a in expected:
        body.append("\t{ " + ", ".join(str(int(v)) for v in a) + " },")
    body.append("};")
    (SRC / "test_images.c").write_text("\n".join(body) + "\n")

    print(f"{n} images exported (MNIST indices {chosen})")
    for i, lab, a in zip(chosen, labels, expected):
        p = int(a.argmax())
        print(f"  #{i:5d} true {lab} -> PC predicts {p} ({(int(a[p]) + 128) / 256 * 100:.1f} %)"
              f"{'' if p == lab else '   <- error'}")


if __name__ == "__main__":
    main()
